"""Rhino-path byte identity (Requirements 11.9, 17.6).

Runs the pipeline exactly as the Grasshopper Slice button does (system Python 3.10,
`-m pipeline <spec> --project <Designer>`, cwd Scripts, cleaned environment) on a temp copy
of the Fixture inputs, and compares combined_output.gcode with the Fixture gcode after
removing only the Orca timestamp line.

The pipeline writes its output into dirname(spec_dir), so everything lands in the temp
folder and the real Designer/output folder is never touched.
"""

import difflib
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from pnp_server.normalize import normalize_gcode

ORCA_EXE = Path(r"C:\Program Files\OrcaSlicer\orca-slicer.exe")
FIXTURE_INPUTS = ("spec.json", "housing.3mf", "part-2.stl")
STRIPPED_ENV = ("PYTHONHOME", "PYTHONPATH", "PYTHONNOUSERSITE", "PYTHONSTARTUP", "PYTHONSAFEPATH")


def _python_cmd():
    launcher = shutil.which("py")
    if launcher:
        return [launcher, "-3.10"]
    return [sys.executable]


def _clean_env():
    env = dict(os.environ)
    for key in STRIPPED_ENV:
        env.pop(key, None)
    return env


def test_normalize_removes_only_timestamp_line():
    data = b"; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2 on 2026-11-03 at 11:04:31\n; total layer number: 7\n"
    assert normalize_gcode(data) == b"; HEADER_BLOCK_START\n; total layer number: 7\n"
    assert normalize_gcode(data.decode()) == "; HEADER_BLOCK_START\n; total layer number: 7\n"


@pytest.mark.orca
@pytest.mark.skipif(not ORCA_EXE.exists(), reason="OrcaSlicer exe not installed")
def test_rhino_path_identical(tmp_path, fixture_dir, designer_dir):
    spec_dir = tmp_path / "spec"
    spec_dir.mkdir()
    for name in FIXTURE_INPUTS:
        shutil.copyfile(fixture_dir / name, spec_dir / name)

    cmd = _python_cmd() + ["-m", "pipeline", str(spec_dir), "--project", str(designer_dir)]
    proc = subprocess.run(
        cmd,
        cwd=str(designer_dir / "Scripts"),
        env=_clean_env(),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        timeout=600,
    )
    log = proc.stdout.decode("utf-8", errors="replace")
    assert proc.returncode == 0, "pipeline failed:\n" + log[-8000:]

    produced_path = tmp_path / "combined_output.gcode"
    assert produced_path.exists(), "no combined_output.gcode written:\n" + log[-8000:]

    produced = normalize_gcode(produced_path.read_bytes())
    expected = normalize_gcode((fixture_dir / "combined_output.gcode").read_bytes())
    if produced != expected:
        diff = difflib.unified_diff(
            expected.decode("utf-8", errors="replace").splitlines(),
            produced.decode("utf-8", errors="replace").splitlines(),
            "fixture/combined_output.gcode",
            "pipeline/combined_output.gcode",
            lineterm="",
            n=2,
        )
        lines = list(diff)
        print("\n".join(lines[:400]))
        pytest.fail(
            "combined_output.gcode differs from the Fixture after normalisation "
            "({} diff lines, first 400 printed)".format(len(lines))
        )
