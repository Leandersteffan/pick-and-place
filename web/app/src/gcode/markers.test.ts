import { describe, expect, it } from 'vitest'
import fixture from '../../../fixtures/demo-v1/combined_output.gcode?raw'
import { lex } from './lexer'
import {
  RE_ANY3, RE_BOUNDARY, isRecognisedMacro, isRecognisedNoopCommand, matchMarker, type MarkerMatch,
} from './markers'

describe('matchMarker on concrete lines', () => {
  it('matches placement groups, including late and fallback', () => {
    expect(matchMarker(';=== Layer 11 Placement ===')).toEqual({
      kind: 'placement_group', label: 'Layer 11 Placement', layer: 11, variant: 'layer',
    })
    expect(matchMarker(';=== Late Placement After Last Print Move ===')).toEqual({
      kind: 'placement_group', label: 'Late Placement After Last Print Move', layer: null, variant: 'late',
    })
    expect(matchMarker(';=== Fallback Late Placement ===')).toEqual({
      kind: 'placement_group', label: 'Fallback Late Placement', layer: null, variant: 'fallback',
    })
  })

  it('matches the part markers', () => {
    expect(matchMarker(';Placing PCB #3')).toEqual({ kind: 'placing', label: 'Placing PCB #3', partKind: 'PCB', number: 3 })
    expect(matchMarker(';Placing TRACE_CLOTH #1')).toEqual({
      kind: 'placing', label: 'Placing TRACE_CLOTH #1', partKind: 'TRACE_CLOTH', number: 1,
    })
    expect(matchMarker(';=== Pick and Place: PCB ===')).toEqual({ kind: 'pnp_header', label: 'Pick and Place: PCB', partKind: 'PCB' })
    expect(matchMarker(';Tamping 2 Points')).toEqual({ kind: 'tamping', label: 'Tamping 2 Points', count: 2 })
    expect(matchMarker(';Pick Sequence')).toEqual({ kind: 'pick_seq', label: 'Pick Sequence' })
    expect(matchMarker(';Place Sequence')).toEqual({ kind: 'place_seq', label: 'Place Sequence' })
    expect(matchMarker(';Starting Prinjection Sequence for PCB holes')).toEqual({
      kind: 'prinjection', label: 'Starting Prinjection Sequence for PCB holes',
    })
    expect(matchMarker(';Nozzle Wipe Sequence')).toEqual({ kind: 'wipe', label: 'Nozzle Wipe Sequence' })
  })

  it('treats other three-= markers as unknown and ignores Orca =====-banners', () => {
    expect(matchMarker(';=== Something New ===')).toEqual({ kind: 'unknown_marker', label: 'Something New' })
    expect(matchMarker(';===== date: 20251222 =====================')).toBeNull()
    expect(RE_ANY3.test(';===== date: 20260605 =====')).toBe(false)
    expect(matchMarker(';==== four ====')).toBeNull()
  })

  it('matches Context_Boundary comments', () => {
    const b = (t: string) => matchMarker(t) as Extract<MarkerMatch, { kind: 'boundary' }> | null
    expect(b(';Z:2.2')?.boundary).toBe('z')
    expect(b(';TYPE:Outer wall')?.boundary).toBe('type')
    expect(b(';LAYER_CHANGE')?.boundary).toBe('layer_change')
    expect(b('; printing object housing.3mf id:0 copy 0')?.boundary).toBe('printing_object')
    expect(b('; stop printing object housing.3mf id:0 copy 0')?.boundary).toBe('stop_printing_object')
    expect(RE_BOUNDARY.test(';LAYER_CHANGE_X')).toBe(false)
    expect(matchMarker(';WIDTH:0.45')).toBeNull()
    expect(matchMarker(';WIPE_START')).toBeNull()
  })

  it('matches skipped extrusion and the Orca timestamp', () => {
    expect(matchMarker('; skipped E-1, nozzle is below 170 C')).toEqual({
      kind: 'skipped_extrusion', label: 'skipped E-1, nozzle is below 170 C', e: -1, minTemp: 170,
    })
    expect(matchMarker('; skipped E-2.5, nozzle is below 170 C')).toMatchObject({ e: -2.5, minTemp: 170 })
    expect(matchMarker('; generated by OrcaSlicer 2.4.2 on 2026-11-03 at 11:04:31')).toEqual({ kind: 'stamp' })
    expect(matchMarker('; generated by PrusaSlicer 2.8 on 2026-11-03')).toBeNull()
  })
})

describe('recognised command lists', () => {
  it('knows the no-op macros and word commands', () => {
    for (const name of ['SET_PRESSURE_ADVANCE', 'PRINT_START', 'PRINT_END', 'BED_MESH_CALIBRATE', 'TIMELAPSE_TAKE_FRAME',
      'EXCLUDE_OBJECT_DEFINE', 'EXCLUDE_OBJECT_START']) {
      expect(isRecognisedMacro(name)).toBe(true)
    }
    expect(isRecognisedMacro('MY_NEW_MACRO')).toBe(false)
    expect(isRecognisedMacro('PAUSE')).toBe(false)
    for (const code of ['M140', 'M204', 'M486', 'M73', 'T0', 'T1', 'G21']) expect(isRecognisedNoopCommand(code)).toBe(true)
    expect(isRecognisedNoopCommand('G1')).toBe(false)
    expect(isRecognisedNoopCommand('M999')).toBe(false)
  })
})

describe('Fixture marker scan', () => {
  const found: Record<string, number[]> = {}
  const matches: { line: number; m: MarkerMatch }[] = []
  for (const t of lex(fixture)) {
    if (t.kind !== 'comment') continue
    const m = matchMarker(t.text)
    if (m === null) continue
    const key = m.kind === 'boundary' ? `boundary:${m.boundary}` : m.kind
    ;(found[key] ??= []).push(t.line)
    matches.push({ line: t.line, m })
  }
  const labelsAt = (kind: string) => matches.filter((x) => x.m.kind === kind).map((x) => [x.line, 'label' in x.m ? x.m.label : ''])

  it('finds the placement groups, part markers and sequences at their lines', () => {
    expect(labelsAt('placement_group')).toEqual([[6574, 'Layer 11 Placement'], [6854, 'Layer 12 Placement']])
    expect(labelsAt('placing')).toEqual([[6576, 'Placing PCB #3'], [6856, 'Placing TRACE_CLOTH #1'], [6903, 'Placing TRACE_CLOTH #2']])
    expect(labelsAt('pnp_header')).toEqual([
      [6577, 'Pick and Place: PCB'], [6857, 'Pick and Place: TRACE_CLOTH'], [6904, 'Pick and Place: TRACE_CLOTH'],
    ])
    expect(found.pick_seq).toEqual([6590, 6870, 6917])
    expect(found.place_seq).toEqual([6600, 6882, 6929])
    expect(found.prinjection).toEqual([6618])
    expect(found.tamping).toEqual([6893, 6940])
    expect(found.wipe).toEqual([3818, 6580, 6619, 6654, 6860, 6907, 6950])
    expect(found.unknown_marker).toBeUndefined()
  })

  it('finds the skipped extrusions and the timestamp', () => {
    expect(found.skipped_extrusion).toEqual([6605, 6609])
    expect(found.stamp).toEqual([2])
  })

  it('counts the Context_Boundary comments', () => {
    expect(found['boundary:type'].length).toBe(192)
    expect(found['boundary:layer_change'].length).toBe(32)
    expect(found['boundary:z'].length).toBe(32)
    expect(found['boundary:printing_object'].length).toBe(32)
    expect(found['boundary:stop_printing_object'].length).toBe(32)
    expect(found['boundary:layer_change'].slice(0, 8)).toEqual([134, 797, 2284, 2506, 2726, 2947, 3402, 3830])
    expect(found['boundary:z'].slice(0, 2)).toEqual([135, 798])
  })

  it('does not match any of the twelve Orca =====-banners', () => {
    const banners = lex(fixture).filter((t) => t.kind === 'comment' && t.text.startsWith(';====='))
    expect(banners.length).toBe(12)
    for (const t of banners) expect(t.kind === 'comment' && matchMarker(t.text)).toBeNull()
  })

  it('recognises every macro and no-op word command left over in the Fixture', () => {
    const handledWords = new Set(['G0', 'G1', 'G2', 'G3', 'G4', 'G17', 'G28', 'G90', 'G91', 'G92', 'M82', 'M83', 'M104', 'M106', 'M107', 'M109'])
    const left: string[] = []
    for (const t of lex(fixture)) {
      if (t.kind === 'macro' && t.name !== 'TEMPERATURE_WAIT' && !isRecognisedMacro(t.name)) left.push(t.name)
      if (t.kind === 'word' && !handledWords.has(t.code) && !isRecognisedNoopCommand(t.code)) left.push(t.code)
    }
    expect(left).toEqual([])
  })
})
