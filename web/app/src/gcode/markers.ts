// Comment marker matching and the recognised-command lists. Pure: no DOM, no three.js.
//
// The Assembly_Markers are written by Scripts/pipeline/assemble.py
// (writer.comment(...)); the Context_Boundary and timestamp comments come from Orca.
// Input is the trimmed comment line including its leading `;` (CommentToken.text).

/** `;=== Layer N Placement ===`, `;=== Late Placement After Last Print Move ===`, `;=== Fallback Late Placement ===` */
export const RE_GROUP = /^;=== (?:Layer (\d+) Placement|(Late Placement After Last Print Move)|(Fallback Late Placement)) ===$/
/** `;=== Pick and Place: PCB ===` */
export const RE_PNP = /^;=== Pick and Place: ([A-Z_]+) ===$/
/** Any other exactly-three-`=` marker. Orca's `;===== date: ... =====` fails because the fourth character is `=`. */
export const RE_ANY3 = /^;=== (?!=)(.+?) ===$/
/** `;Placing PCB #3` (number is 1-based) */
export const RE_PLACING = /^;Placing ([A-Z_]+) #(\d+)$/
/** `;Tamping 2 Points` */
export const RE_TAMPING = /^;Tamping (\d+) Points$/
/** Literal sequence markers. */
export const LIT = {
  ';Pick Sequence': 'pick_seq',
  ';Place Sequence': 'place_seq',
  ';Starting Prinjection Sequence for PCB holes': 'prinjection',
  ';Nozzle Wipe Sequence': 'wipe',
} as const satisfies Record<string, 'pick_seq' | 'place_seq' | 'prinjection' | 'wipe'>
/** Context_Boundary: `;Z:`, `;TYPE:`, `;LAYER_CHANGE`, `; printing object`, `; stop printing object` */
export const RE_BOUNDARY = /^;(?:Z:|TYPE:|LAYER_CHANGE$|LAYER:-?\d+\s*$)|^; (?:printing object|stop printing object)/
/** Cura's layer comment `;LAYER:12` (not `;LAYER_COUNT:`). */
export const RE_CURA_LAYER = /^;LAYER:-?\d+\s*$/
/** `; skipped E-1, nozzle is below 170 C` (gcode_writer blocks filament moves below 170 C on Klipper) */
export const RE_SKIPPED = /^; skipped E(-?[\d.]+), nozzle is below (\d+) C$/
/** Orca header timestamp, ignored by the gcode diff. */
export const RE_STAMP = /^; generated by OrcaSlicer \S+ on .+$/

export type BoundaryKind = 'z' | 'type' | 'layer_change' | 'cura_layer' | 'printing_object' | 'stop_printing_object'

export type MarkerMatch =
  | { kind: 'placement_group'; label: string; layer: number | null; variant: 'layer' | 'late' | 'fallback' }
  | { kind: 'pnp_header'; label: string; partKind: string }
  | { kind: 'placing'; label: string; partKind: string; number: number }
  | { kind: 'tamping'; label: string; count: number }
  | { kind: 'pick_seq' | 'place_seq' | 'prinjection' | 'wipe'; label: string }
  | { kind: 'unknown_marker'; label: string }
  | { kind: 'boundary'; boundary: BoundaryKind }
  | { kind: 'skipped_extrusion'; label: string; e: number; minTemp: number }
  | { kind: 'stamp' }

/** Assembly_Marker kinds, i.e. the marker kinds that become Timeline Events. */
export const ASSEMBLY_MARKER_KINDS = [
  'placement_group', 'placing', 'pnp_header', 'pick_seq', 'place_seq', 'tamping', 'prinjection', 'wipe',
] as const

function boundaryKind(text: string): BoundaryKind {
  if (text.startsWith(';Z:')) return 'z'
  if (text.startsWith(';TYPE:')) return 'type'
  if (text === ';LAYER_CHANGE') return 'layer_change'
  if (RE_CURA_LAYER.test(text)) return 'cura_layer'
  if (text.startsWith('; stop printing object')) return 'stop_printing_object'
  return 'printing_object'
}

/**
 * Classifies one trimmed comment line. Returns null for ordinary comments
 * (Orca settings, `;WIDTH:`, `;===== ... =====` banners and so on).
 */
export function matchMarker(text: string): MarkerMatch | null {
  const c = text.charCodeAt(1)
  if (c === 61 /* = */) {
    let m = RE_GROUP.exec(text)
    if (m !== null) {
      if (m[1] !== undefined) {
        return { kind: 'placement_group', label: `Layer ${m[1]} Placement`, layer: parseInt(m[1], 10), variant: 'layer' }
      }
      return m[2] !== undefined
        ? { kind: 'placement_group', label: m[2], layer: null, variant: 'late' }
        : { kind: 'placement_group', label: m[3], layer: null, variant: 'fallback' }
    }
    m = RE_PNP.exec(text)
    if (m !== null) return { kind: 'pnp_header', label: `Pick and Place: ${m[1]}`, partKind: m[1] }
    m = RE_ANY3.exec(text)
    if (m !== null) return { kind: 'unknown_marker', label: m[1] }
    return null
  }
  let m = RE_PLACING.exec(text)
  if (m !== null) return { kind: 'placing', label: `Placing ${m[1]} #${m[2]}`, partKind: m[1], number: parseInt(m[2], 10) }
  m = RE_TAMPING.exec(text)
  if (m !== null) return { kind: 'tamping', label: `Tamping ${m[1]} Points`, count: parseInt(m[1], 10) }
  if (Object.prototype.hasOwnProperty.call(LIT, text)) {
    return { kind: LIT[text as keyof typeof LIT], label: text.slice(1) }
  }
  if (RE_BOUNDARY.test(text)) return { kind: 'boundary', boundary: boundaryKind(text) }
  m = RE_SKIPPED.exec(text)
  if (m !== null) {
    return { kind: 'skipped_extrusion', label: text.slice(2), e: Number(m[1]), minTemp: parseInt(m[2], 10) }
  }
  if (RE_STAMP.test(text)) return { kind: 'stamp' }
  return null
}

