/** Macro name prefixes that are recognised, e.g. `EXCLUDE_OBJECT_DEFINE`. */
export const RECOGNISED_MACRO_PREFIXES: readonly string[] = ['EXCLUDE_OBJECT_']

const MACRO_SET = new Set(RECOGNISED_MACROS)
const NOOP_SET = new Set(RECOGNISED_NOOP_COMMANDS)

export function isRecognisedMacro(name: string): boolean {
  return MACRO_SET.has(name) || RECOGNISED_MACRO_PREFIXES.some((p) => name.startsWith(p))
}

/** `code` is a normalised WordToken.code such as 'M204' or 'T0'. */
export function isRecognisedNoopCommand(code: string): boolean {
  return NOOP_SET.has(code) || /^T\d+$/.test(code)
}
